"""研究 skill：按问题拆开的判断标准与回答结构。

系统提示词只讲"怎么选 skill"，不写任何一问的判据；模型先调用
``load_skill`` 取到完整判据，再按判据取数、作答。这样新增一问只要
往 ``SKILLS`` 里加一项，不必改提示词里的路由。

每个 skill 是纯文本，不依赖数据库和网络，便于测试。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Skill:
    name: str
    title: str
    description: str
    instructions: str


BUSINESS_MODEL = Skill(
    name="business_model",
    title="第一问：这家公司究竟靠什么赚钱？",
    description="拆解商业模式：卖什么、卖给谁、收入与利润来自哪里",
    instructions="""第一问：这家公司究竟靠什么赚钱？

判断标准：能用三句话向没有金融知识的人解释清楚它如何赚钱；说不清就说明还没看懂，不要急着做后面的判断。

回答顺序：
1. 三句话：卖什么、卖给谁、为什么客户愿意付钱。
2. 拆收入：主要产品/地区的收入、占比、同比、毛利率，指出真正的利润来源。占比和毛利率要一起看，收入大的业务不一定最赚钱。
3. 看成本与利润质量：主要成本项、毛利率水平、费用率。工具数据里没有非经常性损益时，明确写「资料不足」，不要猜。
4. 写 2-3 条关键不确定点：哪个数据最可能被误读、哪块业务最看不懂。

取数建议：get_company_profile 看主营描述与行业；get_segments 看产品与地区构成；get_finance 看最新一期毛利率、净利率与费用趋势；get_announcements 看是否有重大变化。对照另一家公司时分别取数、分别引用。""",
)

MOAT = Skill(
    name="moat",
    title="第二问：竞争优势是什么？能持续多久？",
    description="按五类护城河找证据，判断优势能否被对手侵蚀",
    instructions="""第二问：竞争优势是什么？能持续多久？

判断标准：不是看过去利润率高不高，而是解释为什么竞争对手不能轻易侵蚀它的利润。说不清"对手为什么做不到"，就只是描述结果，不是竞争优势。

第一步：按五类逐项判断，每类给出「有证据 / 证据不足 / 不适用」，不要五类都写成有优势：
- 品牌优势：客户是否愿意为它多付钱，或点名购买。证据看毛利率能否长期高于同行、提价后销量是否稳住。
- 成本优势：是否因规模、工艺、资源或区位而长期比对手便宜。证据看毛利率与费用率能否在降价周期里守住。
- 网络效应：用户越多，产品或平台对每个用户越有价值。证据看用户/商家数量与留存是否互相拉动。
- 转换成本：客户换供应商是否要付出金钱、时间或风险。证据看续约率、粘性、替换周期。
- 规模或渠道优势：是否拥有对手短期复制不了的产能、网点、经销体系或供应链。证据看单位成本、覆盖密度、单点效率。

第二步：每条成立的判断按三段式写：
1. 证据：引用具体数据（毛利率、费用率、份额、分部毛利率等），没有数据就不下判断。
2. 推断：这个证据为什么构成优势，作用机制是什么。
3. 对手为何难以复制：复制需要什么、需要多久、卡在哪里。

第三步：用 get_financial_history 取 5-10 年年度序列，看毛利率、净利率、费用率、ROE 是否稳定或改善；大起大落说明优势可能不牢。用 get_segments 看各分部毛利率，判断定价权来自哪块业务。

第四步：主动写竞争侵蚀路径：降价、技术替代、渠道扩张、政策变化，哪条最可能发生、为什么，发生时先看哪个指标恶化。

第五步：给 2-3 条可证伪的观察指标，写成"如果 X 在 Y 时间内跌破/超过 Z，说明判断失效"，让用户以后能自己验证。

禁止：
- 高毛利本身不是护城河，必须解释高毛利为什么不会被竞争抹平。
- 没有同业成本、份额或客户数据时，写「资料不足」，不要用"品牌力强""渠道壁垒高"这类空话补位。
- 不要因为历史增长快就默认优势能持续；上市时间短的，明确说明样本不足。""",
)

SKILLS: dict[str, Skill] = {skill.name: skill for skill in (BUSINESS_MODEL, MOAT)}


def catalog() -> list[dict]:
    """返回 skill 目录的副本，供工具描述与测试使用。"""
    return [
        {"name": skill.name, "title": skill.title, "description": skill.description}
        for skill in SKILLS.values()
    ]


def get_skill(name) -> Skill | None:
    """按名称取 skill；名称不合法时返回 ``None``。"""
    return SKILLS.get(name) if isinstance(name, str) else None
