"""研究 skill：按问题拆开的判断标准与回答结构。

系统提示词只讲"怎么选 skill"，不写任何一问的判据；模型先调用
``load_skill`` 取到完整判据，再按判据取数、作答。这样新增一问只要
往 ``SKILLS`` 里加一项，不必改提示词里的路由。

每个 skill 是纯文本，不依赖数据库和网络，便于测试。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Skill:
    name: str
    title: str
    description: str
    instructions: str


