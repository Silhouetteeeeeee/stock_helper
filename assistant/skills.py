"""研究 skill：按问题拆开的判断标准与回答结构。

系统提示词只讲"怎么选 skill"，不写任何一问的判据；模型先调用
``load_skill`` 取到完整判据，再按判据取数、作答。这样新增一问只要
往 ``SKILLS`` 里加一项，不必改提示词里的路由。

每个 skill 是纯文本，不依赖数据库和网络，便于测试。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Skill:
    name: str
    title: str
    description: str
    instructions: str


BUSINESS_MODEL = Skill(
    name="business_model",
    title="第一问：这家公司究竟靠什么赚钱？",
    description="拆解商业模式：卖什么、卖给谁、收入与利润来自哪里",
    instructions="""第一问：这家公司究竟靠什么赚钱？

判断标准：能用三句话向没有金融知识的人解释清楚它如何赚钱；说不清就说明还没看懂，不要急着做后面的判断。

回答顺序：
1. 三句话：卖什么、卖给谁、为什么客户愿意付钱。
2. 拆收入：主要产品/地区的收入、占比、同比、毛利率，指出真正的利润来源。占比和毛利率要一起看，收入大的业务不一定最赚钱。
3. 看成本与利润质量：主要成本项、毛利率水平、费用率。工具数据里没有非经常性损益时，明确写「资料不足」，不要猜。
4. 写 2-3 条关键不确定点：哪个数据最可能被误读、哪块业务最看不懂。

取数建议：get_company_profile 看主营描述与行业；get_segments 看产品与地区构成；get_finance 看最新一期毛利率与净利率；费用率及其多年趋势用 get_financial_history 的年度序列（销售、管理、研发费用率都在里面）；get_announcements 看是否有重大变化。对照另一家公司时分别取数、分别引用。""",
)

MOAT = Skill(
    name="moat",
    title="第二问：竞争优势是什么？能持续多久？",
    description="按五类护城河找证据，判断优势能否被对手侵蚀",
    instructions="""第二问：竞争优势是什么？能持续多久？

判断标准：不是看过去利润率高不高，而是解释为什么竞争对手不能轻易侵蚀它的利润。说不清"对手为什么做不到"，就只是描述结果，不是竞争优势。

第一步：按五类逐项判断，每类给出「有证据 / 证据不足 / 不适用」，不要五类都写成有优势：
- 品牌优势：客户是否愿意为它多付钱，或点名购买。证据看毛利率能否长期高于同行、提价后销量是否稳住。
- 成本优势：是否因规模、工艺、资源或区位而长期比对手便宜。证据看毛利率与费用率能否在降价周期里守住。
- 网络效应：用户越多，产品或平台对每个用户越有价值。证据看用户/商家数量与留存是否互相拉动。
- 转换成本：客户换供应商是否要付出金钱、时间或风险。证据看续约率、粘性、替换周期。
- 规模或渠道优势：是否拥有对手短期复制不了的产能、网点、经销体系或供应链。证据看单位成本、覆盖密度、单点效率。

第二步：每条成立的判断按三段式写：
1. 证据：引用具体数据（毛利率、费用率、份额、分部毛利率等），没有数据就不下判断。
2. 推断：这个证据为什么构成优势，作用机制是什么。
3. 对手为何难以复制：复制需要什么、需要多久、卡在哪里。

第三步：用 get_financial_history 取 5-10 年年度序列，看毛利率、净利率、费用率、ROE 是否稳定或改善；大起大落说明优势可能不牢。用 get_segments 看各分部毛利率，判断定价权来自哪块业务。

第四步：主动写竞争侵蚀路径：降价、技术替代、渠道扩张、政策变化，哪条最可能发生、为什么，发生时先看哪个指标恶化。

第五步：给 2-3 条可证伪的观察指标，写成"如果 X 在 Y 时间内跌破/超过 Z，说明判断失效"，让用户以后能自己验证。

禁止：
- 高毛利本身不是护城河，必须解释高毛利为什么不会被竞争抹平。
- 没有同业成本、份额或客户数据时，写「资料不足」，不要用"品牌力强""渠道壁垒高"这类空话补位。
- 不要因为历史增长快就默认优势能持续；上市时间短的，明确说明样本不足。""",
)

OPERATING_HISTORY = Skill(
    name="operating_history",
    title="第三问：过去 5–10 年的经营表现如何？",
    description="看长期增长、盈利能力与现金流，判断利润质量",
    instructions="""第三问：过去 5–10 年的经营表现如何？

判断标准：不只看某一年赚了多少钱，而是看长期趋势和利润质量；目标是找到能跨越周期、持续维持盈利能力、且利润能变成现金的公司。只有一两年数据时，明确说样本不足。

逐项看：
1. 营收：是否持续增长，有没有大起大落或停滞；增速在加快还是放缓。
2. 净利润：是否与营收同向；利润增速长期高于营收，是靠经营改善还是一次性项目。非经常性损益没有拆分时写「资料不足」。
3. 盈利能力：毛利率、净利率、ROE 的区间和趋势；ROE 很高时要看是不是高杠杆推起来的。ROIC 目前没有现成数据，写「资料不足」，不要拿 ROE 冒充。
4. 现金流：经营现金流/净利润是否长期接近或高于 1；经营现金流与自由现金流是否为正、是否随扩张恶化。自由现金流为负要如实指出，并区分是主动资本开支还是经营失血。
5. 费用与负债：销售、管理费用率是否稳定，资产负债率有没有随扩张明显抬升。
6. 异常年份：找出最差的一年，说明是周期、一次性事件还是趋势恶化，用公告交叉验证。

回答结构：
1. 先给逐年摘要（营收、净利、毛利率、净利率、ROE、经营现金流/净利、自由现金流），至少覆盖 5 年；不足 5 年要标注。
2. 分三段下判断：增长稳不稳、盈利高不高且稳不稳、赚的是不是真钱。
3. 结论落在四种状态之一：持续改善 / 高位稳定 / 周期波动但无恶化 / 明显恶化，并说明依据。
4. 给 2–3 条未来可验证的观察指标。

取数：必须调用 get_financial_history 取年度序列；get_finance 看最新一期明细；get_announcements 解释异常年份。对照另一家公司时分别取数、分别引用。

禁止：
- 只用最近一年或单季数据下长期结论。
- 把投资收益、补贴、资产处置等非经常性项目当成主营利润。
- 用 ROE 代替 ROIC，或对银行/保险套用毛利率、费用率口径（这类公司该口径不可比）。
- 现金流为负时只报数字、不解释来源。""",
)

FINANCIAL_SAFETY = Skill(
    name="financial_safety",
    title="第四问：财务安全吗？会不会因为一次危机就撑不住？",
    description="看有息负债、利息保障、商誉与营运资金，做坏年份压力测试",
    instructions="""第四问：财务安全吗？会不会因为一次危机就撑不住？

判断标准：不是看资产负债率高低，而是看坏年份来临时它能不能自己活下来。重点是有息负债、短期到期的债务、现金和利息支出，以及商誉、应收、存货这些"看着是资产、出事时变不成钱"的项目。

逐项看：
1. 有息负债：短期借款、一年内到期非流动负债、长期借款、应付债券、租赁负债合计；短期有息负债占多少，货币资金能不能覆盖。资产负债率只是参考，不同行业差异很大，不要机械套用"超过 70% 就不安全"。
2. 利息保障：利润总额加利息费用，再除以利息费用。低于 3 倍要警惕，低于 1.5 倍说明利润稍一下滑就还不上利息。工具会标明用的是利息费用还是财务费用近似。
3. 营运资金：应收账款、存货的增速是否持续快于营收；经营现金流/净利润是否长期低于 1。赊销冲收入、压货堆库存，最后都会变成减值和坏账。
4. 商誉：绝对额与占净资产比例。占比高、且被并购标的增长乏力时，减值会直接吃掉利润；用公告交叉验证并购与减值。
5. 股东权益稀释：定增、可转债、大额股权激励会摊薄每股价值；数据里没有股本变动时写「资料不足」，有公告就引用公告。
6. 压力测试：假设营收连续 2–3 年下滑 20%–30%、毛利率再降 5–10 个百分点、融资环境收紧，经营现金流是否仍为正、现金能否覆盖短期债务与利息。缺少分项成本数据时，给出测算假设并标明是估算，不要伪装成精确结果。

回答结构：
1. 先列安全垫：货币资金、有息负债、短期有息负债、利息保障倍数、商誉占净资产比例、应收/存货同比。
2. 再做 2–3 个坏年份情景的压力测试，写清假设。
3. 结论落在三档之一：安全（现金覆盖短债、利息保障充足）/ 需要关注（某一项偏紧）/ 脆弱（短债覆盖不足或利息保障过低），并说明触发条件。
4. 给 2–3 条可验证的观察指标。

取数：get_finance 取有息负债、利息保障、商誉、应收/存货同比；get_financial_history 看多年负债率与现金流；get_announcements 找商誉减值、定增、可转债、股权激励。对照另一家公司时分别取数、分别引用。

禁止：
- 只看资产负债率就下结论，或把高负债直接等同于危险。
- 对银行、保险等金融机构套用有息负债和利息保障口径（存款不是有息负债，利息支出也不是费用），这类公司明确写「口径不可比」。
- 不区分受限资金；数据没有时写「资料不足」。
- 用估算的压力测试冒充财报事实。""",
)

SKILLS: dict[str, Skill] = {
    skill.name: skill
    for skill in (BUSINESS_MODEL, MOAT, OPERATING_HISTORY, FINANCIAL_SAFETY)
}


def catalog() -> list[dict]:
    """返回 skill 目录的副本，供工具描述与测试使用。"""
    return [
        {"name": skill.name, "title": skill.title, "description": skill.description}
        for skill in SKILLS.values()
    ]


def get_skill(name) -> Skill | None:
    """按名称取 skill；名称不合法时返回 ``None``。"""
    return SKILLS.get(name) if isinstance(name, str) else None
